using AudioEffector.Domain.Entities;
using AudioEffector.Domain.ValueObjects;

namespace AudioEffector.Application.Common;

/// <summary>
/// 機器転送時に同梱対象とする `.lrc` 歌詞ファイルの種別別オプションを表します
/// </summary>
public sealed class LrcTransferOptions
{
    /// <summary>
    /// 自動生成以外（手動作成・外部取得等）の `.lrc` ファイルを転送対象に含めるかどうかを取得または設定します
    /// </summary>
    public bool TransferManualLrcFiles { get; init; }

    /// <summary>
    /// テキストファイルからの強制アライメントで自動生成した `.lrc` ファイルを転送対象に含めるかどうかを取得または設定します
    /// </summary>
    public bool TransferTextAlignedLrcFiles { get; init; }

    /// <summary>
    /// 音声からの直接文字起こしで自動生成した `.lrc` ファイルを転送対象に含めるかどうかを取得または設定します
    /// </summary>
    public bool TransferTranscribedLrcFiles { get; init; }

    /// <summary>
    /// いずれかの `.lrc` 種別の同梱転送が有効かどうかを取得します
    /// </summary>
    public bool IsAnyEnabled =>
        TransferManualLrcFiles || TransferTextAlignedLrcFiles || TransferTranscribedLrcFiles;

    /// <summary>
    /// 指定された生成元種別の `.lrc` ファイルが転送対象かどうかを判定します
    /// </summary>
    /// <param name="originType">判定対象の生成元種別</param>
    /// <returns>転送対象の場合は <see langword="true"/></returns>
    public bool ShouldTransfer(LrcOriginType originType)
    {
        return originType switch
        {
            LrcOriginType.ManualOrExternal => TransferManualLrcFiles,
            LrcOriginType.AutoGeneratedTextAlignment => TransferTextAlignedLrcFiles,
            LrcOriginType.AutoGeneratedAudioTranscription => TransferTranscribedLrcFiles,
            _ => false,
        };
    }

    /// <summary>
    /// <see cref="AppSettings"/> から <see cref="LrcTransferOptions"/> を構築します
    /// </summary>
    /// <param name="settings">アプリケーション設定（<see langword="null"/> 時はすべて無効）</param>
    /// <returns>構築された <see cref="LrcTransferOptions"/></returns>
    public static LrcTransferOptions FromSettings(AppSettings? settings)
    {
        if (settings == null)
        {
            return new LrcTransferOptions();
        }

        return new LrcTransferOptions
        {
            TransferManualLrcFiles = settings.TransferManualLrcFiles,
            TransferTextAlignedLrcFiles = settings.TransferTextAlignedLrcFiles,
            TransferTranscribedLrcFiles = settings.TransferTranscribedLrcFiles,
        };
    }
}
