namespace AudioEffector.Domain.ValueObjects;

/// <summary>
/// `.lrc` 同期歌詞ファイルの生成元種別を表す列挙体です
/// </summary>
public enum LrcOriginType
{
    /// <summary>
    /// 自動生成以外（手動作成・外部取得、または識別メタデータ未付与の既存 `.lrc`）
    /// </summary>
    ManualOrExternal = 0,

    /// <summary>
    /// テキストファイルからの強制アライメントにより自動生成された `.lrc`
    /// </summary>
    AutoGeneratedTextAlignment = 1,

    /// <summary>
    /// 音声からの直接文字起こしにより自動生成された `.lrc`
    /// </summary>
    AutoGeneratedAudioTranscription = 2,
}
