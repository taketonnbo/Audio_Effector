using System;
using System.IO;
using System.Text;
using AudioEffector.Application.Common;
using AudioEffector.Domain.Entities;
using AudioEffector.Domain.Services;
using AudioEffector.Domain.ValueObjects;
using Moq;
using Xunit;

namespace AudioEffector.Application.Tests.Common;

/// <summary>
/// <see cref="LrcTransferOptions"/> および <see cref="CompanionLrcResolver"/> の種別判定・文字コード・64KB上限・例外耐性を検証するテストクラス
/// </summary>
public sealed class CompanionLrcResolverTests : IDisposable
{
    private readonly string _tempDir;

    /// <summary>
    /// テスト用の一時ディレクトリを初期化します。
    /// </summary>
    public CompanionLrcResolverTests()
    {
        _tempDir = Path.Combine(Path.GetTempPath(), $"AE_CompanionLrc_{Guid.NewGuid():N}");
        Directory.CreateDirectory(_tempDir);
    }

    /// <summary>
    /// テスト用の一時ディレクトリを破棄します。
    /// </summary>
    public void Dispose()
    {
        try
        {
            if (Directory.Exists(_tempDir))
            {
                Directory.Delete(_tempDir, recursive: true);
            }
        }
        catch
        {
            // クリーンアップ失敗は無視
        }
    }

    /// <summary>
    /// LrcTransferOptions の FromSettings(null)、IsAnyEnabled、および全 LrcOriginType に対する ShouldTransfer 判定を検証します。
    /// </summary>
    [Fact]
    public void LrcTransferOptions_FromSettingsとShouldTransfer_各種別および未定義値が正しく判定されること()
    {
        // Arrange
        var fromNull = LrcTransferOptions.FromSettings(null);
        var fromSettings = LrcTransferOptions.FromSettings(new AppSettings
        {
            TransferManualLrcFiles = true,
            TransferTextAlignedLrcFiles = false,
            TransferTranscribedLrcFiles = true,
        });

        // Act & Assert
        Assert.False(fromNull.IsAnyEnabled);
        Assert.False(fromNull.ShouldTransfer(LrcOriginType.ManualOrExternal));
        Assert.False(fromNull.ShouldTransfer(LrcOriginType.AutoGeneratedTextAlignment));
        Assert.False(fromNull.ShouldTransfer(LrcOriginType.AutoGeneratedAudioTranscription));

        Assert.True(fromSettings.IsAnyEnabled);
        Assert.True(fromSettings.ShouldTransfer(LrcOriginType.ManualOrExternal));
        Assert.False(fromSettings.ShouldTransfer(LrcOriginType.AutoGeneratedTextAlignment));
        Assert.True(fromSettings.ShouldTransfer(LrcOriginType.AutoGeneratedAudioTranscription));
        Assert.False(fromSettings.ShouldTransfer((LrcOriginType)999));
    }

    /// <summary>
    /// UTF-8（BOM あり・なし）・UTF-16 LE BOM・Shift-JIS 相当バイト列の各 .lrc ファイルから ASCII [re:...] タグを壊さずに読み取り判定できることを検証します。
    /// </summary>
    [Fact]
    public void TryResolveCompanionLrcPath_各種文字コードのLrcファイル_ASCIIタグが正しく読み取られ判定されること()
    {
        // Arrange
        Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);
        string utf8Audio = Path.Combine(_tempDir, "utf8.mp3");
        string utf8BomAudio = Path.Combine(_tempDir, "utf8bom.mp3");
        string utf16Audio = Path.Combine(_tempDir, "utf16.mp3");
        string sjisAudio = Path.Combine(_tempDir, "sjis.mp3");

        File.WriteAllText(Path.ChangeExtension(utf8Audio, ".lrc"), "[re:Audio Effector (TextAlignment)]\n[00:01.00]日本語歌詞", new UTF8Encoding(false));
        File.WriteAllText(Path.ChangeExtension(utf8BomAudio, ".lrc"), "[re:Audio Effector (AudioTranscription)]\n[00:01.00]BOM付き歌詞", new UTF8Encoding(true));
        File.WriteAllText(Path.ChangeExtension(utf16Audio, ".lrc"), "[re:Audio Effector (TextAlignment)]\n[00:01.00]UTF16歌詞", new UnicodeEncoding(bigEndian: false, byteOrderMark: true));
        File.WriteAllText(Path.ChangeExtension(sjisAudio, ".lrc"), "[re:Audio Effector (TextAlignment)]\n[00:01.00]シフトJIS歌詞", Encoding.GetEncoding(932));

        var parserMock = new Mock<ILrcParser>();
        parserMock.Setup(p => p.ClassifyOrigin(It.Is<string>(s => s.Contains("Audio Effector (TextAlignment)", StringComparison.Ordinal))))
            .Returns(LrcOriginType.AutoGeneratedTextAlignment);
        parserMock.Setup(p => p.ClassifyOrigin(It.Is<string>(s => s.Contains("Audio Effector (AudioTranscription)", StringComparison.Ordinal))))
            .Returns(LrcOriginType.AutoGeneratedAudioTranscription);

        var textAlignedOnly = new LrcTransferOptions { TransferTextAlignedLrcFiles = true };
        var transcribedOnly = new LrcTransferOptions { TransferTranscribedLrcFiles = true };

        // Act
        bool resolvedUtf8 = CompanionLrcResolver.TryResolveCompanionLrcPath(utf8Audio, textAlignedOnly, parserMock.Object, out string utf8Lrc);
        bool resolvedUtf8Bom = CompanionLrcResolver.TryResolveCompanionLrcPath(utf8BomAudio, transcribedOnly, parserMock.Object, out string utf8BomLrc);
        bool resolvedUtf16 = CompanionLrcResolver.TryResolveCompanionLrcPath(utf16Audio, textAlignedOnly, parserMock.Object, out string utf16Lrc);
        bool resolvedSjis = CompanionLrcResolver.TryResolveCompanionLrcPath(sjisAudio, textAlignedOnly, parserMock.Object, out string sjisLrc);

        // Assert
        Assert.True(resolvedUtf8);
        Assert.Equal(Path.ChangeExtension(utf8Audio, ".lrc"), utf8Lrc);
        Assert.True(resolvedUtf8Bom);
        Assert.Equal(Path.ChangeExtension(utf8BomAudio, ".lrc"), utf8BomLrc);
        Assert.True(resolvedUtf16);
        Assert.Equal(Path.ChangeExtension(utf16Audio, ".lrc"), utf16Lrc);
        Assert.True(resolvedSjis);
        Assert.Equal(Path.ChangeExtension(sjisAudio, ".lrc"), sjisLrc);
    }

    /// <summary>
    /// 64 KB を超える大容量 .lrc ファイルであっても先頭 64 KB（65,536 バイト）以内で読み込みが打ち切られることを検証します。
    /// </summary>
    [Fact]
    public void TryResolveCompanionLrcPath_64KB超の大容量ファイル_先頭64KB以内で読み込みが打ち切られること()
    {
        // Arrange
        string audioPath = Path.Combine(_tempDir, "huge.mp3");
        string lrcPath = Path.ChangeExtension(audioPath, ".lrc");
        string padding = new string('A', 70 * 1024);
        File.WriteAllText(lrcPath, $"{padding}\n[re:Audio Effector (TextAlignment)]\n", new UTF8Encoding(false));

        string? capturedHeader = null;
        var parserMock = new Mock<ILrcParser>();
        parserMock.Setup(p => p.ClassifyOrigin(It.IsAny<string>()))
            .Callback<string>(text => capturedHeader = text)
            .Returns(LrcOriginType.ManualOrExternal);

        var options = new LrcTransferOptions { TransferManualLrcFiles = true };

        // Act
        bool resolved = CompanionLrcResolver.TryResolveCompanionLrcPath(audioPath, options, parserMock.Object, out string resolvedPath);

        // Assert
        Assert.True(resolved);
        Assert.Equal(lrcPath, resolvedPath);
        Assert.NotNull(capturedHeader);
        Assert.Equal(64 * 1024, capturedHeader!.Length);
        Assert.DoesNotContain("TextAlignment", capturedHeader, StringComparison.Ordinal);
    }

    /// <summary>
    /// 全設定無効・パーサー未指定・ファイル不在・パーサー例外・ファイルロックによる読取例外時に例外を投げず安全に false を返すことを検証します。
    /// </summary>
    [Fact]
    public void TryResolveCompanionLrcPath_無効条件および読取やパーサー例外時_安全にfalseを返し警告コールバックが呼ばれること()
    {
        // Arrange
        string audioPath = Path.Combine(_tempDir, "locked.mp3");
        string lrcPath = Path.ChangeExtension(audioPath, ".lrc");
        File.WriteAllText(lrcPath, "[00:01.00]lyric");

        var throwingParser = new Mock<ILrcParser>();
        throwingParser.Setup(p => p.ClassifyOrigin(It.IsAny<string>()))
            .Throws(new InvalidOperationException("parse boom"));

        var manualEnabled = new LrcTransferOptions { TransferManualLrcFiles = true };
        var allDisabled = new LrcTransferOptions();

        Exception? parserWarningEx = null;
        Exception? ioWarningEx = null;

        // Act 1: 全無効・パーサー null・ファイル不在
        bool disabledResult = CompanionLrcResolver.TryResolveCompanionLrcPath(audioPath, allDisabled, throwingParser.Object, out _);
        bool nullParserResult = CompanionLrcResolver.TryResolveCompanionLrcPath(audioPath, manualEnabled, null, out _);
        bool missingFileResult = CompanionLrcResolver.TryResolveCompanionLrcPath(Path.Combine(_tempDir, "missing.mp3"), manualEnabled, throwingParser.Object, out _);

        // Act 2: パーサー例外
        bool parserThrowResult = CompanionLrcResolver.TryResolveCompanionLrcPath(
            audioPath,
            manualEnabled,
            throwingParser.Object,
            out _,
            onWarning: (_, ex) => parserWarningEx = ex);

        // Act 3: 排他ロック中の読取例外
        bool ioThrowResult;
        using (new FileStream(lrcPath, FileMode.Open, FileAccess.ReadWrite, FileShare.None))
        {
            var okParser = new Mock<ILrcParser>();
            ioThrowResult = CompanionLrcResolver.TryResolveCompanionLrcPath(
                audioPath,
                manualEnabled,
                okParser.Object,
                out _,
                onWarning: (_, ex) => ioWarningEx = ex);
        }

        // Assert
        Assert.False(disabledResult);
        Assert.False(nullParserResult);
        Assert.False(missingFileResult);
        Assert.False(parserThrowResult);
        Assert.IsType<InvalidOperationException>(parserWarningEx);
        Assert.False(ioThrowResult);
        Assert.IsAssignableFrom<IOException>(ioWarningEx);
    }
}
